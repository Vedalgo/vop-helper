function initDrugSearch() {
  const searchInput = document.getElementById('drug-search');
  const filterSelect = document.getElementById('drug-filter');
  const resultsContainer = document.getElementById('drug-results');
  const statsContainer = document.getElementById('drug-stats');

  if (!searchInput || !resultsContainer) return;

  function renderDrugs() {
    const query = searchInput.value.toLowerCase().trim();
    const filter = filterSelect.value;
    
    const filtered = DRUGS_DB.filter(drug => {
      const matchesQuery = drug.name.toLowerCase().includes(query) || drug.form.toLowerCase().includes(query);
      const matchesFilter = filter === 'all' || drug.category === filter;
      return matchesQuery && matchesFilter;
    });

    statsContainer.textContent = `Найдено препаратов: ${filtered.length}`;

    if (filtered.length === 0) {
      resultsContainer.innerHTML = '<p style="text-align:center; color:var(--muted); padding: 20px;">Ничего не найдено.</p>';
      return;
    }

    resultsContainer.innerHTML = filtered.map(drug => {
      let badgeText = '';
      let badgeClass = '';
      if (drug.category === 'subsidized') { badgeText = 'Льготный (Т1)'; badgeClass = 'subsidized'; }
      else if (drug.category === 'diseases') { badgeText = 'По заболеваниям (Т2)'; badgeClass = 'diseases'; }
      else if (drug.category === 'pharmacy') { badgeText = 'В аптеках (Т3)'; badgeClass = 'pharmacy'; }

      return `
        <div class="drug-item">
          <div class="drug-item-header">
            <span class="drug-name">${drug.name}</span>
            <span class="drug-badge ${badgeClass}">${badgeText}</span>
          </div>
          <div class="drug-form"><b>Форма:</b> ${drug.form}</div>
          ${drug.note ? `<div class="drug-note">Примечание: ${drug.note}</div>` : ''}
        </div>
      `;
    }).join('');
  }

  searchInput.addEventListener('input', renderDrugs);
  filterSelect.addEventListener('change', renderDrugs);
  renderDrugs();
}
document.addEventListener('DOMContentLoaded', initDrugSearch);